// Writes the generated reference pages (gitignored) from the package's JSON schemas.
// Runs under plain Node before `vitepress dev|build`; `dungeonmaker-js` resolves to the built dist/.
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import designSchema from 'dungeonmaker-js/design.schema.json' with { type: 'json' };
import dungeonSchema from 'dungeonmaker-js/dungeon.schema.json' with { type: 'json' };
import { cellLegendTable, DUNGEON_OMITTED, fieldTable, schemaRows } from './reference.mjs';

const siteFile = (path) => fileURLToPath(new URL(`../${path}`, import.meta.url));

function write(path, content) {
  const file = siteFile(path);
  mkdirSync(new URL('.', `file://${file}`), { recursive: true });
  writeFileSync(file, `${content.trimEnd()}\n`);
}

const rows = schemaRows(designSchema);

const intro = `---
outline: [2, 3]
---

# Design config reference

<!-- Generated by scripts/generate-reference.mjs from design.schema.json. Do not edit. -->

A design is a JSON document that \`createDungeon\` and \`createDungeonMaker\` accept next to the
legacy design text. This page lists every field with its type, its limits and the upstream record
of DungeonMaker 2.05 it maps to. The coordinate convention is the one from [Orientation](/guide/orientation): \`x\` is
the column, \`y\` the row, north is up.

Point your editor at the schema to get completion and hover texts:

\`\`\`json
{ "$schema": "./node_modules/dungeonmaker-js/design.schema.json" }
\`\`\`

The same schema ships in the package as \`dungeonmaker-js/design.schema.json\`. The
\`$schema\` key is ignored by the parser. To check a design in code use \`validateDesign\`
from \`dungeonmaker-js/schema\`; on the command line use \`dungeonmaker-js validate\`. Both
run the same semantic checks as the generator, so a design that validates also generates.

Fields marked *optional* can be left out; the Default column says what that means.
`;

const sections = Object.entries(designSchema.properties)
  .filter(([key]) => key !== '$schema')
  .map(([key, node]) => {
    const own = rows.filter(
      (r) => r.path === key || r.path.startsWith(`${key}.`) || r.path.startsWith(`${key}[`),
    );
    const summary = own[0]?.description ?? node.description ?? '';
    return `## ${key}\n\n${summary}\n\n${fieldTable(own)}\n`;
  });

const schemaRow = rows.filter((r) => r.path === '$schema');
write(
  'reference/config.md',
  `${intro}\n## $schema\n\n${fieldTable(schemaRow)}\n\n${sections.join('\n')}`,
);

write('reference/_dungeon-fields.md', fieldTable(schemaRows(dungeonSchema), DUNGEON_OMITTED));
write('guide/_cell-legend.md', cellLegendTable());
