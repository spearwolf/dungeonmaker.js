// Writes the committed design artifacts (design.schema.json, dungeon.schema.json and the preset modules in
// src/presets/) from the built package. Run via `pnpm --filter dungeonmaker-js generate`
// (builds first); the drift test in packages/dungeonmaker-js/test/validate.test.ts fails
// if the committed schema is stale, the preset tests if a preset differs from its vendor file.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const pkgUrl = new URL('../packages/dungeonmaker-js/', import.meta.url);
const vendorUrl = new URL('../native/vendor/dungeonmaker-2.05/', import.meta.url);
const pkg = fileURLToPath(pkgUrl);

const DESIGNS = [
  'design',
  'design2',
  'design3A',
  'design3WithTunnelers',
  'design4A',
  'design5',
  'design6',
  'design7',
  'designEmpty',
  'designEmpty2',
  'designOld1',
];

async function importBuilt(relative) {
  const file = fileURLToPath(new URL(relative, pkgUrl));
  if (!existsSync(file)) {
    console.error(
      `Missing build output ${file}.\nRun \`pnpm --filter dungeonmaker-js generate\` (it builds first).`,
    );
    process.exit(1);
  }
  return import(pathToFileURL(file).href);
}

const { DesignConfigSchema } = await importBuilt('dist/schema.js');
const { DungeonFileSchema } = await importBuilt('dist/schema/dungeon-file.js');
const { parseDesignText } = await importBuilt('dist/config/parse.js');

const written = [];
const write = (relative, text) => {
  const file = fileURLToPath(new URL(relative, pkgUrl));
  writeFileSync(file, text);
  written.push(file);
};

write('design.schema.json', `${JSON.stringify(DesignConfigSchema, null, 2)}\n`);
write('dungeon.schema.json', `${JSON.stringify(DungeonFileSchema, null, 2)}\n`);

mkdirSync(new URL('src/presets/', pkgUrl), { recursive: true });
for (const name of DESIGNS) {
  const config = parseDesignText(readFileSync(new URL(name, vendorUrl), 'utf8'));
  write(
    `src/presets/${name}.ts`,
    `// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by scripts/generate-design-artifacts.mjs from native/vendor/dungeonmaker-2.05/${name}
// (DungeonMaker 2.05 sample design, © Peter Henningsen). Do not edit by hand.
import type { DesignConfig } from '../schema/model.js';

export const ${name}: DesignConfig = ${JSON.stringify(config, null, 2)};
`,
  );
}

// Biome lints JSON and TS in this repo; normalise the output so a rerun is a no-op.
execFileSync('pnpm', ['exec', 'biome', 'format', '--write', ...written], {
  cwd: pkg,
  stdio: 'inherit',
});
