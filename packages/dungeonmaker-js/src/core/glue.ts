/** The parts of the Emscripten module (wasm/dungeonmaker.js) this package uses. */
export interface DungeonMakerWasmModule {
  readonly HEAPU8: Uint8Array;
  _dm_generate(designTextPtr: number, seed: number, flags: number): number;
  _dm_width(): number;
  _dm_height(): number;
  _dm_cells(): number;
  _dm_last_error(): number;
  _dm_reset(): void;
  _malloc(size: number): number;
  _free(ptr: number): void;
  stringToUTF8(str: string, outPtr: number, maxBytesToWrite: number): void;
  lengthBytesUTF8(str: string): number;
  UTF8ToString(ptr: number): string;
}

export interface DungeonMakerWasmModuleArg {
  instantiateWasm?(
    imports: WebAssembly.Imports,
    done: (instance: WebAssembly.Instance, module?: WebAssembly.Module) => void,
  ): object;
  print?(line: string): void;
  printErr?(line: string): void;
}

// The glue is generated by Emscripten and ships without types. This relative path
// is valid from src/core/ and from dist/core/ alike, so wasm/ stays build output only.
// @ts-expect-error untyped Emscripten glue
import factory from '../../wasm/dungeonmaker.js';

export const loadDungeonMakerWasm = factory as (
  moduleArg?: DungeonMakerWasmModuleArg,
) => Promise<DungeonMakerWasmModule>;
